#!/usr/bin/env python3
"""Write fixtures/MANIFEST.md: what each fixture workbook contains, read from its XML.

Without arguments, rewrite the manifest. With --check, exit with status 1 when
the committed manifest differs from what the fixtures produce.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
FIXTURES = ROOT / "fixtures"
OUTPUT = FIXTURES / "MANIFEST.md"

if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from tests import excel_facts as facts  # noqa: E402

_HEADER = """\
# Fixture manifest

What each workbook in `fixtures/` contains, read from its XML. Generated by
`python scripts/describe_fixtures.py`; do not edit by hand.
`tests/test_fixture_manifest.py` fails when this file no longer matches the
fixtures. [`scripts/excel_fixtures/`](../scripts/excel_fixtures/README.md)
explains how the Excel-authored fixtures and the `excel-reference/` pairs were
made.

Drawing anchors are written as `cell (+column offset, +row offset)` in EMU,
from the anchor's `xdr:from` to its `xdr:to`. Conditional-format rules are
listed in priority order; `x14` marks a rule or validation that lives only in
the worksheet's extension list, and `x14:` inside a rule shows its extension
twin and the range it covers.
"""


def workbooks() -> list[Path]:
    """Every fixture workbook: the top-level ones, then the excel-reference pairs."""
    top = [p for p in FIXTURES.iterdir() if _is_workbook(p)]
    pairs = [p for p in (FIXTURES / "excel-reference").glob("*/*") if _is_workbook(p)]
    return sorted(top, key=lambda p: p.name.lower()) + sorted(pairs, key=lambda p: p.as_posix())


def _is_workbook(path: Path) -> bool:
    """An ``.xlsx`` or ``.xlsm`` file, not the ``~$`` lock file Excel keeps while one is open."""
    return path.suffix.lower() in (".xlsx", ".xlsm") and not path.name.startswith("~$")


def _code(text) -> str:
    return f"`{text}`"


def _marker(marker: tuple[int, int, int, int] | None) -> str:
    if marker is None:
        return "?"
    col, col_off, row, row_off = marker
    return f"{facts.col_letters(col + 1)}{row + 1} (+{col_off}, +{row_off})"


def _anchor(anchor: facts.Anchor) -> str:
    kind = anchor.kind + (f' editAs="{anchor.edit_as}"' if anchor.edit_as else "")
    if anchor.kind == "absoluteAnchor":
        where = f"at {anchor.position} size {anchor.extent}"
    elif anchor.kind == "oneCellAnchor":
        where = f"{_marker(anchor.start)} size {anchor.extent}"
    else:
        where = f"{_marker(anchor.start)} to {_marker(anchor.end)}"
    objects = ", ".join(f"{kind} {name!r}" for kind, name in anchor.objects) or "nothing"
    return f"{kind} {where}: {objects}"


def _table(table: facts.Table) -> list[str]:
    parts = [f"{table.header_rows} header row", f"{table.totals_rows} totals row"]
    if table.autofilter:
        parts.append(f"autoFilter {_code(table.autofilter)}")
    if table.sort:
        ref, conditions = table.sort
        keys = ", ".join(f"{_code(r)} {'descending' if d else 'ascending'}" for r, d in conditions)
        parts.append(f"sorted {_code(ref)} by {keys}")
    if table.style:
        parts.append(_code(table.style))
    lines = [f"- Table {_code(table.name)} {_code(table.ref)}: {'; '.join(parts)}"]
    for col in table.columns:
        details = []
        if col.formula:
            details.append(f"calculated {_code(col.formula)}")
        if col.totals:
            details.append(f"totals {_code(col.totals)}")
        if col.data_format:
            details.append(f"data format {_code(col.data_format)}")
        lines.append(f"  - {_code(col.name)}" + (f": {'; '.join(details)}" if details else ""))
    return lines


def _formulas(summary: dict) -> str:
    kinds = ", ".join(f"{kind} {count}" for kind, count in summary["kinds"].items())
    parts = [kinds]
    if summary["shared_groups"]:
        parts.append(f"{summary['shared_groups']} shared group(s)")
    if summary["cross_sheet"]:
        parts.append(f"{summary['cross_sheet']} with a sheet reference")
    if summary["future_functions"]:
        parts.append(f"_xlfn: {', '.join(summary['future_functions'])}")
    return "; ".join(parts)


def describe(path: Path) -> list[str]:
    book = facts.Book(path)
    tables = facts.tables(book)
    formats = facts.conditional_formats(book)
    validations = facts.data_validations(book)
    anchors = facts.drawings(book)
    merges = facts.merges(book)
    formulas = facts.formula_summary(book)
    features = facts.sheet_features(book)
    lines = [f"## {_code(path.relative_to(FIXTURES).as_posix())}", ""]
    parts = facts.package_parts(book)
    lines.append(
        "- Parts: " + (", ".join(f"{name} {count}" for name, count in parts.items()) or "none")
    )
    names = facts.defined_names(book)
    if names:
        listed = ", ".join(
            f"{_code(name)}{f' (local to {scope})' if scope else ''} = {_code(text)}"
            for (name, scope), text in sorted(names.items())
        )
        lines.append(f"- Defined names: {listed}")
    for sheet in book.sheets:
        lines += ["", f"### {_code(sheet.name)}" + (f" ({sheet.state})" if sheet.state != "visible" else ""), ""]
        body = []
        if sheet.name in merges:
            body.append(f"- Merges: {', '.join(_code(m) for m in merges[sheet.name])}")
        for table in tables.get(sheet.name, ()):
            body += _table(table)
        if sheet.name in formats:
            body.append("- Conditional formatting:")
            for rule in formats[sheet.name]:
                source = f" ({rule.source})" if rule.source else ""
                body.append(f"  - {_code(rule.sqref)} {rule.type}{source}: {_code(rule.detail)}")
        if sheet.name in validations:
            body.append("- Data validation:")
            for dv in validations[sheet.name]:
                source = " (x14)" if dv.source else ""
                body.append(f"  - {_code(dv.sqref)} {dv.type}{source}: {_code(dv.detail)}")
        if sheet.name in anchors:
            body.append("- Drawing anchors:")
            body += [f"  - {_anchor(a)}" for a in anchors[sheet.name]]
        if sheet.name in formulas:
            body.append(f"- Formulas: {_formulas(formulas[sheet.name])}")
        body += [f"- {line}" for line in features.get(sheet.name, ())]
        lines += body or ["- No tables, formats, validations, drawings, merges or formulas."]
    return lines


def _index(paths: list[Path]) -> list[str]:
    lines = [
        "| Workbook | Sheets | Tables | CF rules | Validations | Drawing anchors | Formulas |",
        "| --- | --- | --- | --- | --- | --- | --- |",
    ]
    for path in paths:
        book = facts.Book(path)
        counts = [
            len(book.sheets),
            sum(len(t) for t in facts.tables(book).values()),
            sum(len(r) for r in facts.conditional_formats(book).values()),
            sum(len(v) for v in facts.data_validations(book).values()),
            sum(len(a) for a in facts.drawings(book).values()),
            sum(sum(s["kinds"].values()) for s in facts.formula_summary(book).values()),
        ]
        name = path.relative_to(FIXTURES).as_posix()
        lines.append(f"| {_code(name)} | " + " | ".join(str(c) for c in counts) + " |")
    return lines


def render() -> str:
    """Return the manifest text."""
    paths = workbooks()
    lines = [_HEADER, *_index(paths)]
    for path in paths:
        lines += ["", *describe(path)]
    return "\n".join(lines) + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check",
        action="store_true",
        help="report a stale manifest with exit status 1 instead of rewriting it",
    )
    args = parser.parse_args(argv)
    text = render()
    current = OUTPUT.read_text(encoding="utf-8") if OUTPUT.is_file() else None
    if current == text:
        return 0
    if args.check:
        print(
            f"{OUTPUT.relative_to(ROOT).as_posix()} is stale; run scripts/describe_fixtures.py",
            file=sys.stderr,
        )
        return 1
    OUTPUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {OUTPUT.relative_to(ROOT).as_posix()}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
